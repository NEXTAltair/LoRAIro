"""Select tracked, portable Git hooks without rewriting generated OS-specific hooks."""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path


def install(root: Path) -> None:
    hook = root / ".githooks/pre-commit"
    if not hook.is_file():
        raise ValueError("The tracked pre-commit hook is missing")
    configured = subprocess.run(
        ["git", "-C", str(root), "config", "--get", "core.hooksPath"],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()
    if configured and configured != ".githooks":
        raise ValueError("An existing custom core.hooksPath is configured; preserve and integrate it first")
    if not configured:
        path = subprocess.check_output(
            ["git", "-C", str(root), "rev-parse", "--path-format=absolute", "--git-path", "hooks"],
            text=True,
        ).strip()
        for existing in Path(path).glob("*"):
            if not existing.is_file() or existing.name.endswith(".sample"):
                continue
            content = existing.read_text(encoding="utf-8", errors="replace")
            generated = existing.name == "pre-commit" and "File generated by pre-commit" in content
            lfs = existing.name in {"post-checkout", "post-merge", "pre-push"} and (
                f"git lfs {existing.name}" in content
            )
            if not (generated or lfs):
                raise ValueError(f"Existing custom Git hook {existing.name} must be integrated first")
    # Local Git config is isolated with the checkout; a relative path works in worktrees too.
    subprocess.run(["git", "-C", str(root), "config", "--local", "core.hooksPath", ".githooks"], check=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", type=Path, default=Path(__file__).resolve().parents[1])
    try:
        install(parser.parse_args().target)
    except ValueError as error:
        parser.exit(1, f"Git hook setup failed: {error}\n")
